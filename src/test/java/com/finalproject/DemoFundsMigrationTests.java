package com.finalproject;

import com.finalproject.db.migration.V10__demo_pending_funds;
import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;

import java.math.BigDecimal;
import java.sql.DriverManager;
import java.util.UUID;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

class DemoFundsMigrationTests {
    @Test void backfillPreservesExistingIncomeAndRefundsAndIsIdempotent() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:funds-" + UUID.randomUUID() + ";MODE=MSSQLServer", "sa", "")) {
            var jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
            jdbc.execute("CREATE TABLE commissions (id BIGINT PRIMARY KEY, cost DECIMAL(18,2))");
            jdbc.execute("CREATE TABLE stores (id BIGINT PRIMARY KEY, e_wallet DECIMAL(18,2), commission_id BIGINT)");
            jdbc.execute("CREATE TABLE orders (id BIGINT PRIMARY KEY, pickup_store_id BIGINT, status VARCHAR(20), payment_status VARCHAR(20), payment_method VARCHAR(20), total_amount DECIMAL(18,2))");
            jdbc.execute("CREATE TABLE payments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT, method VARCHAR(20), status VARCHAR(20), amount DECIMAL(18,2), momo_environment VARCHAR(16), transaction_code VARCHAR(100))");
            jdbc.execute("CREATE TABLE transactions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_id BIGINT, order_id BIGINT, amount DECIMAL(18,2), is_up BOOLEAN, type VARCHAR(30), status VARCHAR(20), request_key VARCHAR(80) UNIQUE, description VARCHAR(500), created_at TIMESTAMP)");
            jdbc.update("INSERT INTO commissions VALUES (1, 40)");
            jdbc.update("INSERT INTO stores VALUES (1, 200000, 1)");
            for (int id = 1; id <= 8; id++) {
                String status = id == 2 || id == 5 ? "COMPLETED" : id == 3 ? "REFUNDED" : "PENDING";
                String payment = id == 3 ? "REFUNDED" : id == 4 ? "UNPAID" : "PAID";
                jdbc.update("INSERT INTO orders VALUES (?, 1, ?, ?, 'MOMO_DEMO', 100000)", id, status, payment);
                jdbc.update("INSERT INTO payments (order_id, method, status, amount, momo_environment, transaction_code) VALUES (?, 'MOMO_DEMO', ?, ?, 'demo', ?)",
                        id, id == 3 ? "REFUNDED" : id == 4 ? "PENDING" : "SUCCESS", id == 6 ? 1 : 100000, "DEMO-MOMO-" + id);
            }
            jdbc.update("INSERT INTO transactions (store_id, order_id, amount, is_up, type, status, request_key) VALUES (1, 2, 90000, TRUE, 'ORDER_PAYMENT', 'COMPLETED', 'legacy-income')");
            jdbc.update("INSERT INTO transactions (store_id, order_id, amount, is_up, type, status, request_key) VALUES (1, 8, 100000, FALSE, 'REFUND', 'COMPLETED', 'legacy-refund')");
            jdbc.update("INSERT INTO payments (order_id, method, status, amount, momo_environment, transaction_code) VALUES (7, 'MOMO_DEMO', 'SUCCESS', 100000, 'demo', 'DEMO-MOMO-7')");
            Context context = mock(Context.class);
            when(context.getConnection()).thenReturn(connection);
            var migration = new V10__demo_pending_funds();
            migration.migrate(context);
            migration.migrate(context);
            assertThat(jdbc.queryForObject("SELECT pending_balance FROM stores WHERE id = 1", BigDecimal.class)).isEqualByComparingTo("100000");
            assertThat(jdbc.queryForObject("SELECT e_wallet FROM stores WHERE id = 1", BigDecimal.class)).isEqualByComparingTo("200000");
            assertThat(state(jdbc, 1)).isEqualTo("HELD");
            assertThat(state(jdbc, 2)).isEqualTo("SETTLED");
            assertThat(state(jdbc, 3)).isEqualTo("REFUNDED");
            assertThat(state(jdbc, 4)).isEqualTo("NONE");
            for (int id : new int[]{5, 6, 7, 8}) assertThat(state(jdbc, id)).isEqualTo("REVIEW_REQUIRED");
            assertThat(jdbc.queryForObject("SELECT commission_rate_snapshot FROM orders WHERE id = 1", BigDecimal.class)).isEqualByComparingTo("40");
            assertThat(jdbc.queryForObject("SELECT commission_rate_snapshot FROM orders WHERE id = 2", BigDecimal.class)).isEqualByComparingTo("10");
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM transactions WHERE type = 'PAYMENT_HOLD'", Integer.class)).isEqualTo(1);
            assertThat(jdbc.queryForObject("SELECT wallet_bucket FROM transactions WHERE type = 'ORDER_PAYMENT'", String.class)).isEqualTo("AVAILABLE");
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM orders", Integer.class)).isEqualTo(8);
        }
    }

    private String state(JdbcTemplate jdbc, int id) {
        return jdbc.queryForObject("SELECT funds_status FROM orders WHERE id = ?", String.class, id);
    }
}
