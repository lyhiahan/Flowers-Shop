// Generate a SQL Server migration using the existing entity mappings and seed text.
const fs = require('node:fs');
const path = require('node:path');
const columns = [];
for (const file of fs.readdirSync('src/main/java/com/finalproject/entity')) {
  if (!file.endsWith('.java')) continue;
  const source = fs.readFileSync(path.join('src/main/java/com/finalproject/entity', file), 'utf8');
  const table = source.match(/@Table\(name\s*=\s*"([^"]+)"/)[1];
  for (const match of source.matchAll(/@org\.hibernate\.annotations\.Nationalized\s+@Column\(([^\r\n]*)\)\s+private String (\w+)/g)) {
    const column = match[1].match(/name\s*=\s*"([^"]+)"/)?.[1] || match[2].replace(/[A-Z]/g, c => '_' + c.toLowerCase());
    if (table !== 'products') columns.push([table, column]);
  }
}
const originals = new Set();
for (const file of ['src/main/java/com/finalproject/config/DataInitializer.java', 'src/main/java/com/finalproject/service/ProductSeederService.java', 'database.sql', 'src/main/resources/db/repair-schema.sql']) {
  const source = fs.readFileSync(file, 'utf8');
  const pattern = file.endsWith('.java') ? /"([^"\r\n]+)"/g : /N?'((?:[^']|'')*)'/g;
  for (const match of source.matchAll(pattern)) {
    const value = match[1].replace(/''/g, "'");
    if (value.length >= 4 && /[^\x00-\x7f]/.test(value) && !value.includes('?') && !value.includes('\\')) originals.add(value);
  }
}
const quote = s => "N'" + s.replaceAll("'", "''") + "'";
const sql = `-- Generated by scripts/build-ui-unicode-repair.cjs. No guessed replacement text.
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;
CREATE TABLE #Columns (table_name NVARCHAR(128), column_name NVARCHAR(128));
INSERT INTO #Columns VALUES ${columns.map(c => '(' + c.map(quote).join(',') + ')').join(',\n')};
CREATE TABLE #Originals (value NVARCHAR(2000) COLLATE Latin1_General_100_BIN2);
INSERT INTO #Originals VALUES ${[...originals].map(v => '(' + quote(v) + ')').join(',\n')};
IF OBJECT_ID('dbo.unicode_text_repair_backup') IS NULL
 CREATE TABLE dbo.unicode_text_repair_backup (
  table_name NVARCHAR(128) NOT NULL, column_name NVARCHAR(128) NOT NULL, row_id BIGINT NOT NULL,
  previous_text NVARCHAR(MAX), restored_text NVARCHAR(MAX), repaired_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
  PRIMARY KEY(table_name,column_name,row_id));
DECLARE @table NVARCHAR(128), @column NVARCHAR(128), @length INT, @nullable BIT, @type NVARCHAR(128), @sql NVARCHAR(MAX), @constraint NVARCHAR(128);
DECLARE column_cursor CURSOR LOCAL FAST_FORWARD FOR
 SELECT w.table_name,w.column_name,c.max_length,c.is_nullable,t.name
 FROM #Columns w JOIN sys.tables st ON st.name COLLATE DATABASE_DEFAULT=w.table_name
 JOIN sys.columns c ON c.object_id=st.object_id AND c.name COLLATE DATABASE_DEFAULT=w.column_name
 JOIN sys.types t ON t.user_type_id=c.user_type_id WHERE SCHEMA_NAME(st.schema_id)='dbo';
OPEN column_cursor;
FETCH NEXT FROM column_cursor INTO @table,@column,@length,@nullable,@type;
WHILE @@FETCH_STATUS=0
BEGIN
 IF @type IN ('varchar','char','text')
 BEGIN
  -- Preserve the existing single-column unique constraints during type conversion.
  IF EXISTS (SELECT 1 FROM sys.indexes i JOIN sys.index_columns ic ON ic.object_id=i.object_id AND ic.index_id=i.index_id
   WHERE i.object_id=OBJECT_ID('dbo.'+@table) AND COL_NAME(ic.object_id,ic.column_id)=@column
   AND (i.is_unique_constraint=0 OR i.type<>2 OR (SELECT COUNT(*) FROM sys.index_columns x WHERE x.object_id=i.object_id AND x.index_id=i.index_id)<>1))
   THROW 50001,'Unsupported text index dependency; migration rolled back without removing it.',1;
  SET @constraint=NULL;
  SELECT @constraint=i.name FROM sys.indexes i JOIN sys.index_columns ic ON ic.object_id=i.object_id AND ic.index_id=i.index_id
   WHERE i.object_id=OBJECT_ID('dbo.'+@table) AND COL_NAME(ic.object_id,ic.column_id)=@column AND i.is_unique_constraint=1;
  IF @constraint IS NOT NULL BEGIN
   SET @sql=N'ALTER TABLE dbo.'+QUOTENAME(@table)+N' DROP CONSTRAINT '+QUOTENAME(@constraint); EXEC sp_executesql @sql;
  END;
  SET @sql=N'ALTER TABLE dbo.'+QUOTENAME(@table)+N' ALTER COLUMN '+QUOTENAME(@column)+N' NVARCHAR('
   +CASE WHEN @length=-1 OR @type='text' THEN N'MAX' ELSE CONVERT(NVARCHAR(10),@length) END+N') '+CASE WHEN @nullable=1 THEN N'NULL' ELSE N'NOT NULL' END;
  EXEC sp_executesql @sql;
  IF @constraint IS NOT NULL BEGIN
   SET @sql=N'ALTER TABLE dbo.'+QUOTENAME(@table)+N' ADD CONSTRAINT '+QUOTENAME(@constraint)+N' UNIQUE NONCLUSTERED ('+QUOTENAME(@column)+N')'; EXEC sp_executesql @sql;
  END;
 END;
 -- Only known demo/catalogue fields can be recovered from the source seed text.
 IF @table IN ('stores','users','categories','deliveries','commissions','vouchers','user_levels','store_levels','styles','style_values','user_addresses','reviews')
 BEGIN
  SET @sql=N';WITH candidates AS (
   SELECT d.id,MIN(o.value) AS restored
   FROM dbo.'+QUOTENAME(@table)+N' d JOIN #Originals o ON LEN(d.'+QUOTENAME(@column)+N')=LEN(o.value)
    AND o.value LIKE REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(CONVERT(NVARCHAR(MAX),d.'+QUOTENAME(@column)+N'),N''!'',N''!!''),N''%'',N''!%''),N''_'',N''!_''),N''['',N''![''),N''?'',N''_'') COLLATE Latin1_General_100_BIN2 ESCAPE N''!''
   WHERE CHARINDEX(N''?'',d.'+QUOTENAME(@column)+N')>0 GROUP BY d.id HAVING COUNT(DISTINCT o.value)=1
  )
  UPDATE d SET '+QUOTENAME(@column)+N'=c.restored
  OUTPUT @t,@c,inserted.id,deleted.'+QUOTENAME(@column)+N',inserted.'+QUOTENAME(@column)+N',SYSDATETIME()
   INTO dbo.unicode_text_repair_backup(table_name,column_name,row_id,previous_text,restored_text,repaired_at)
  FROM dbo.'+QUOTENAME(@table)+N' d JOIN candidates c ON c.id=d.id
  WHERE NOT EXISTS(SELECT 1 FROM dbo.unicode_text_repair_backup b WHERE b.table_name=@t AND b.column_name=@c AND b.row_id=d.id);';
  EXEC sp_executesql @sql,N'@t NVARCHAR(128),@c NVARCHAR(128)',@table,@column;
 END;
 FETCH NEXT FROM column_cursor INTO @table,@column,@length,@nullable,@type;
END;
CLOSE column_cursor; DEALLOCATE column_cursor;
DROP TABLE #Columns; DROP TABLE #Originals;
COMMIT;
SELECT table_name,column_name,COUNT(*) AS repaired_values FROM dbo.unicode_text_repair_backup GROUP BY table_name,column_name;
`;
fs.writeFileSync('sql/migrations/20261003_ui_unicode.sql', sql, 'utf8');
console.log('Generated Unicode migration:', columns.length, 'columns,', originals.size, 'original seed strings');
